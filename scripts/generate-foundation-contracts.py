#!/usr/bin/env python3
"""Generate the reviewed enum lists from the pinned schema, without fetching or changing locks."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
spec = json.loads((root / 'docs/api/spacetraders-openapi-2.3.0.json').read_text())
names = ['WaypointType', 'WaypointTraitSymbol', 'FactionSymbol', 'ShipType', 'TradeSymbol']
lines = ['<?php', '', '// Generated by scripts/generate-foundation-contracts.py from the pinned 2.3.0 schema.', 'return [', "    'enums' => ["]
for name in names:
    values = spec['components']['schemas'][name]['enum']
    lines += [f"        '{name}' => [" + ', '.join(repr(x) for x in values) + '],']
lines += ['    ],', '];', '']
(root / 'config/foundation.php').write_text('\n'.join(lines))
