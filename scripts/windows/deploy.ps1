<#
.SYNOPSIS
Update the production checkout (Herd, spacetraders.test and the tailnet site) to origin/main.
.DESCRIPTION
Run from the production checkout only. Without -Yes it previews the incoming commits and
migrations and changes nothing. With -Yes it backs up, fast-forwards to origin/main,
installs dependencies, migrates, builds, restarts the loopback web server and checks both
addresses. It refuses to run while the local engine is on, on any branch but main, with
uncommitted changes, or outside the spacetraders.test checkout.
.EXAMPLE
.\scripts\windows\deploy.ps1
.EXAMPLE
.\scripts\windows\deploy.ps1 -Yes
#>
param([switch]$Yes)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Invoke-Git {
    param([string[]]$Arguments)
    $result = Invoke-NativeResult 'git.exe' $Arguments
    if ($result.ExitCode -ne 0) { throw "git $($Arguments -join ' ') failed: $($result.Error.Trim())" }
    return $result.Output.Trim()
}

function Invoke-Script {
    param([string]$Name, [string[]]$Arguments = @())
    $result = Invoke-NativeResult 'powershell.exe' (@('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', (Join-Path $PSScriptRoot $Name)) + $Arguments)
    Show-NativeResult $result
    if ($result.ExitCode -ne 0) { throw "$Name $($Arguments -join ' ') failed." }
    return $result.Output
}

function Test-Page {
    param([string]$Url)
    $response = Invoke-WebRequest -Uri $Url -UseBasicParsing -TimeoutSec 60
    if ($response.StatusCode -ne 200) { throw "$Url returned HTTP $($response.StatusCode)." }
    if ($response.Content -match ':5173/') { throw "$Url loads scripts from a Vite dev server; public/hot or a dev process is back." }
    if ($response.Content -notmatch '/build/assets/') { throw "$Url does not reference the built assets." }
    Write-Host "OK: $Url (HTTP 200, built assets)"
}

function Get-TailnetHosts {
    # The published name may be this machine's or a Tailscale Service's, so read what serve actually proxies.
    param([string]$Tailscale, [int]$Port)
    $config = (& $Tailscale serve status --json) -join "`n" | ConvertFrom-Json
    if (-not $config) { return @() }
    $webs = @()
    if ($config.PSObject.Properties.Name -contains 'Web') { $webs += $config.Web }
    if ($config.PSObject.Properties.Name -contains 'Services') {
        foreach ($service in $config.Services.PSObject.Properties.Value) {
            if ($service.PSObject.Properties.Name -contains 'Web') { $webs += $service.Web }
        }
    }
    foreach ($web in $webs) {
        foreach ($site in $web.PSObject.Properties) {
            $proxies = @($site.Value.Handlers.PSObject.Properties.Value | ForEach-Object { $_.Proxy })
            if ($proxies -match "^http://(127\.0\.0\.1|localhost):$Port/?$") { $site.Name -replace ':443$', '' }
        }
    }
}

function Assert-NoDevProcesses {
    param([string]$Root)
    $hot = Join-Path $Root 'public\hot'
    if (Test-Path -LiteralPath $hot) {
        Remove-Item -LiteralPath $hot -Force
        Write-Host 'Removed public\hot (left by a Vite dev server).'
    }
    $vite = @(Get-CimInstance Win32_Process -Filter "Name='node.exe'" | Where-Object { $_.CommandLine -and $_.CommandLine.Contains($Root) -and $_.CommandLine -match 'vite' })
    if ($vite.Count -gt 0) {
        throw "A Vite dev server is running from the production checkout (PID $($vite[0].ProcessId)). Stop it and switch off Herd's automatic dev processes for this site."
    }
}

try {
    . "$PSScriptRoot/common.ps1"
    $root = Get-RepositoryRoot
    $php = Get-HerdPhp
    Write-Host "Production checkout: $root"

    $environment = Get-Content -LiteralPath (Join-Path $root '.env') -ErrorAction Stop
    $appUrl = ($environment | Where-Object { $_ -match '^APP_URL=' } | Select-Object -First 1) -replace '^APP_URL=', ''
    if (([Uri]$appUrl.Trim('"')).Host -ne 'spacetraders.test') { throw "This is not the production checkout (APP_URL is $appUrl). Deploy from C:\Users\taylo\Herd\spacetraders." }
    $branch = Invoke-Git @('branch', '--show-current')
    if ($branch -ne 'main') { throw "Production must be on main, not '$branch'." }
    # public/build is tracked but regenerated by every deploy; any other change means someone edited production.
    # Read porcelain output untrimmed: its two status columns can start with a space (" D path").
    $status = Invoke-NativeResult 'git.exe' @('status', '--porcelain', '--untracked-files=all')
    if ($status.ExitCode -ne 0) { throw "git status failed: $($status.Error.Trim())" }
    $dirty = @($status.Output -split "`r?`n" | Where-Object { $_.Length -gt 3 -and $_.Substring(3) -notlike 'public/build/*' })
    if ($dirty.Count -gt 0) { throw "The production checkout has uncommitted changes outside public/build. Production is never edited in place; resolve them first:`n$($dirty -join "`n")" }

    Invoke-Git @('fetch', '--quiet', 'origin', 'main') | Out-Null
    $head = Invoke-Git @('rev-parse', 'HEAD')
    $target = Invoke-Git @('rev-parse', 'origin/main')
    $ancestor = Invoke-NativeResult 'git.exe' @('merge-base', '--is-ancestor', 'HEAD', 'origin/main')
    if ($ancestor.ExitCode -ne 0) { throw 'origin/main does not contain the deployed commit; a fast-forward is impossible. Investigate before deploying.' }

    if ($head -eq $target) {
        Write-Host "Already at origin/main ($($head.Substring(0, 7)))."
    } else {
        Write-Host "Incoming commits ($($head.Substring(0, 7))..$($target.Substring(0, 7))):"
        Write-Host (Invoke-Git @('log', '--oneline', '--no-decorate', 'HEAD..origin/main'))
        $migrations = Invoke-Git @('diff', '--name-only', '--diff-filter=AM', 'HEAD', 'origin/main', '--', 'database/migrations')
        if ($migrations) { Write-Host "Migrations to run:`n$migrations" } else { Write-Host 'No migrations.' }
    }

    $engine = Invoke-Script 'engine.ps1' @('Status')
    if ($engine -notmatch 'Engine state: off') { throw 'The local engine is not off. End the engine session from the flight deck on spacetraders.test, then deploy again.' }

    if (-not $Yes) {
        Write-Host 'Preview only; nothing changed. Run again with -Yes to deploy.'
        exit 0
    }

    Invoke-Script 'backup.ps1' | Out-Null
    Invoke-Git @('checkout', '--', 'public/build') | Out-Null
    Invoke-Git @('clean', '-fq', '--', 'public/build') | Out-Null
    if ($head -ne $target) { Write-Host (Invoke-Git @('merge', '--ff-only', 'origin/main')) }
    Invoke-Checked $php @((Get-ComposerPhar), 'install', '--no-interaction')
    Invoke-Checked (Get-Pnpm) @('install', '--frozen-lockfile', '--strict-peer-dependencies')
    Invoke-Checked $php @('artisan', 'config:clear')
    Invoke-Checked $php @('artisan', 'migrate', '--force', '--no-interaction')
    Invoke-Checked (Get-Pnpm) @('build')
    Invoke-Checked $php @('artisan', 'optimize:clear')
    Assert-NoDevProcesses $root
    Invoke-Script 'web.ps1' @('Install') | Out-Null

    Test-Page 'http://spacetraders.test/login'
    Test-Page 'http://127.0.0.1:8081/login'
    $tailscale = Join-Path $env:ProgramFiles 'Tailscale\tailscale.exe'
    if (Test-Path -LiteralPath $tailscale) {
        $hosts = @(Get-TailnetHosts $tailscale 8081)
        if ($hosts.Count -eq 0) { Write-Warning 'tailscale serve publishes nothing that proxies to 127.0.0.1:8081; the tailnet site was not checked.' }
        foreach ($name in $hosts) { Test-Page "https://$name/login" }
    }
    Write-Host "Deployed $((Invoke-Git @('rev-parse', '--short', 'HEAD'))) to production."
} catch { [Console]::Error.WriteLine($_.Exception.Message); exit 1 }
