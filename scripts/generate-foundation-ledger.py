#!/usr/bin/env python3
"""Join reviewed source coverage with actual fixture artifacts, without granting foundation acceptance."""
import ast
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
manifest = json.loads((root / 'docs/api/base-api-coverage.json').read_text())
module = ast.parse((root / 'scripts/refresh-foundation-sources.py').read_text())
commands = next(ast.literal_eval(n.value) for n in ast.walk(module) if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'commands' for t in n.targets))
browser = json.loads((root / 'docs/api/evidence/fnd-manual-browser-worker.json').read_text())['operations']
confirmed = {row['command'] for row in browser if row.get('settlement', {}).get('state') == 'confirmed'}
scrap = json.loads((root / 'docs/api/evidence/fnd-scrap-browser-worker.json').read_text())
if scrap['settlement'] == 'confirmed': confirmed.add('scrap')
reads = json.loads((root / 'docs/api/evidence/fnd-reads-browser.json').read_text())['operations']
read_ids = {row['operation'] for row in reads if row['passed']}
rows = []
for operation in manifest['operations']:
    identity = operation['id']
    command = commands.get(identity)
    if operation['method'] == 'GET':
        native = 'Flight deck > API library > ' + identity
        browser_state = 'fixture journey recorded' if identity in read_ids else 'pending'
        artifact = 'evidence/fnd-reads-browser.json'
        contract = 'tests/Feature/FoundationReadTest.php'
    elif identity == 'register':
        native = 'Agents > Create agent > Account token registration'
        browser_state = 'existing UI; registration journey not repeated in this run'
        artifact = None
        contract = 'tests/Feature/AgentTest.php'
    else:
        native = 'Flight deck > Manual API > ' + str(command)
        browser_state = 'fixture preview/approval/worker confirmation recorded' if command in confirmed else 'pending'
        artifact = 'evidence/fnd-scrap-browser-worker.json' if command == 'scrap' else 'evidence/fnd-manual-browser-worker.json'
        contract = 'tests/Feature/FoundationCommandTest.php; tests/Feature/GameplayTest.php; tests/Feature/ExplorationTest.php'
    rows.append({'operation_id': identity, 'method': operation['method'], 'path': operation['path'], 'task': operation['task'],
        'native_path': native, 'request_fields': operation['request_fields'], 'query_fields': operation['query_fields'],
        'source_classification': operation['implementation'], 'contract_tests': contract, 'browser_scope': browser_state,
        'browser_artifact': artifact, 'official_api_acceptance': 'pending', 'foundation_acceptance': 'not_accepted'})
ledger = {'scope': 'Source implementation and synthetic verification. This is not an acceptance-stage record.', 'operations': rows}
(root / 'docs/api/foundation-operation-ledger.json').write_text(json.dumps(ledger, indent=2) + '\n')
lines = ['# Manual capability map', '', 'Generated by `python3 scripts/generate-foundation-ledger.py`. Fixture evidence and official API acceptance are separate. Registration keeps its existing account-token path; all gameplay uses saved agent credentials.', '', '| Operation | Native path | Fixture browser scope | Official API |', '| --- | --- | --- | --- |']
for row in rows:
    lines.append('| `' + row['operation_id'] + '` | ' + row['native_path'] + ' | ' + row['browser_scope'] + ' | Pending |')
(root / 'docs/api/foundation-capability-map.md').write_text('\n'.join(lines) + '\n')
print('Wrote capability map and informational ledger for', len(rows), 'operations. No acceptance was awarded.')
